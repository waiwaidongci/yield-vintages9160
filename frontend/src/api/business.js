import {request} from './client.js';
export const loadAll=async()=>Object.fromEntries(await Promise.all(['sources','periods','inspections','reconciliations','policies','runs','schedules','deliveries','audits'].map(async k=>[k,await request('/'+k)])));
export const saveSource=(data,id)=>request('/sources'+(id?'/'+id:''),id?'PUT':'POST',{data});
export const savePolicy=data=>request('/policies','POST',{data});
export const submitRun=data=>request('/runs','POST',data);
export const approveRun=(id,note)=>request('/runs/'+id+'/approve','POST',{note});
export const importInspections=(period,csv)=>request('/inspections/import','POST',{period,csv});
export const addInspection=data=>request('/inspections','POST',{data});
export const startReconciliation=data=>request('/reconciliations','POST',data);
export const retryReconciliation=id=>request('/reconciliations/'+id+'/retry','POST',{});
